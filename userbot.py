def _render_quote_sticker(name, text, avatar_bytes=None):
    from PIL import Image, ImageDraw
    lines = []
    for raw_line in (text or " ").splitlines()[:8]:
        lines.extend(textwrap.wrap(raw_line, width=28) or [" "])
    lines = lines[:10]
    h = max(160, 95 + len(lines) * 32)
    img = Image.new("RGBA", (512, min(h, 512)), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)

    if avatar_bytes:
        try:
            av = Image.open(BytesIO(avatar_bytes)).convert("RGBA").resize((64, 64))
            mask = Image.new("L", (64, 64), 0)
            ImageDraw.Draw(mask).ellipse((0, 0, 64, 64), fill=255)
            img.paste(av, (12, 16), mask)
        except Exception:
            draw.ellipse((12, 16, 76, 80), fill=(90, 130, 240, 255))
    else:
        draw.ellipse((12, 16, 76, 80), fill=(90, 130, 240, 255))
        draw.text((34, 30), (name[:1] or "U").upper(), fill=(255, 255, 255, 255), font=get_font(28))

    draw.rounded_rectangle((90, 12, 498, min(h - 12, 500)), radius=24, fill=(33, 38, 52, 255))
    draw.text((112, 24), name[:22], fill=(255, 168, 92, 255), font=get_font(22))
    y = 58
    for ln in lines:
        draw.text((112, y), ln, fill=(242, 245, 250, 255), font=get_font(22))
        y += 30

    out = BytesIO()
    out.name = "quote.webp"
    img.save(out, "WEBP")
    out.seek(0)
    return out


