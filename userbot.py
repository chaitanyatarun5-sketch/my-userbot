@client.on(events.NewMessage(pattern=r"\.addsudo(?: |$)(.*)"))
async def addsudo(e):
    if not is_owner(e): return
    arg = e.pattern_match.group(1).strip()
    reply = await e.get_reply_message()
    uid = None
    if arg.isdigit(): uid = int(arg)
    elif reply: uid = reply.sender_id
    elif arg.startswith("@"): await send(e, "**ID chahiye! Use: `.addsudo 123456` ya reply karke `.addsudo`**"); return
    else: await send(e, "**Use: Reply karke `.addsudo` ya `.addsudo 123456`**"); return
    SUDO_USERS.add(uid)
    await send(e, f"**✅ SUDO ADD HO GAYA!**\n**ID:** `{uid}`\nAb ye banda bot chala payega! (Hack wale chod ke) 😎")

@client.on(events.NewMessage(pattern=r"\.remsudo(?: |$)(.*)"))
async def remsudo(e):
    if not is_owner(e): return
    arg = e.pattern_match.group(1).strip()
    reply = await e.get_reply_message()
    uid = int(arg) if arg.isdigit() else (reply.sender_id if reply else None)
    if not uid: await send(e, "**Use: `.remsudo 123456`**"); return
    SUDO_USERS.discard(uid)
    await send(e, f"**❌ SUDO HATA DIYA! ID:** `{uid}`")

