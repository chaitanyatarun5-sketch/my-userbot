def parse_tg_msg_link(link: str):
    clean = link.strip().split("?")[0].rstrip("/")
    # Private supergroup/channel: https://t.me/c/123456789/456 or https://t.me/c/123456789/10/456
    m_priv = re.search(r"t\.me/c/(\d+)/(?:\d+/)?(\d+)$", clean)
    if m_priv:
        return int(f"-100{m_priv.group(1)}"), int(m_priv.group(2))
    # Public group/channel: https://t.me/username/456 or https://t.me/username/10/456
    m_pub = re.search(r"t\.me/([A-Za-z0-9_]+)/(?:\d+/)?(\d+)$", clean)
    if m_pub and m_pub.group(1).lower() != "c":
        return m_pub.group(1), int(m_pub.group(2))
    return None, None


